type InitOptions struct {
	Name         string
	Module       string
	OutputDir    string
	TemplateRoot string
	Force        bool
	WithFrontend bool
	DryRun       bool
	Stdout       io.Writer
	Lang         string
	NoApp        bool
}

var (
	copyEntries = []string{
		".githooks",
		".gitignore",
		"scripts",
		"Makefile",
		"build",
	}
)

// validateProjectName 支持大写字母（CamelCase / PascalCase），用户友好
func validateProjectName(name string) error {
	if name == "" {
		return errors.New("project name cannot be empty")
	}
	if len(name) > 63 {
		return fmt.Errorf("project name too long (max 63 characters)")
	}
	// 允许字母、数字、'-'
	if !regexp.MustCompile(`^[a-zA-Z0-9-]+$`).MatchString(name) {
		return fmt.Errorf(`invalid project name %q: only letters, numbers and '-' are allowed`, name)
	}
	return nil
}

// toKebab 把 CamelCase / PascalCase 转为 kebab-case（内部使用）
func toKebab(s string) string {
	re := regexp.MustCompile(`([a-z0-9])([A-Z])`)
	s = re.ReplaceAllString(s, `$1-$2`)
	return strings.ToLower(s)
}

// InitProject — 三阶段架构
// Phase 1: 核层（所有语言共享）
// Phase 2: 壳层（switch 语言分发）
// Phase 3: 成功消息
func InitProject(opts InitOptions) (err error) {
	name := strings.TrimSpace(opts.Name)
	if name == "" {
		return errors.New("missing project name: use --name")
	}
	if err := validateProjectName(name); err != nil {
		return err
	}
	kebabName := toKebab(name)
	module := strings.TrimSpace(opts.Module)
	if module == "" {
		module = kebabName
	}
	if opts.Stdout == nil {
		opts.Stdout = io.Discard
	}

	templateRoot, err := resolveTemplateRoot(opts.TemplateRoot)
	if err != nil {
		return err
	}

	outputDir, err := resolveOutputDir(opts.OutputDir, kebabName)
	if err != nil {
		return err
	}

	if opts.DryRun {
		printDryRun(opts)
		return nil
	}

	_, statErr := os.Stat(outputDir)
	createdByUs := os.IsNotExist(statErr) && !opts.Force

	if err = ensureOutputDir(outputDir, opts.Force, name); err != nil {
		return err
	}

	defer func() {
		if err != nil && createdByUs {
			slog.Debug("cleanup", "dir", outputDir)
			os.RemoveAll(outputDir)
		}
	}()

	// Phase 1: 核层 — 所有语言共享的部署契约
	for _, entry := range copyEntries {
		src := filepath.Join(templateRoot, entry)
		dst := filepath.Join(outputDir, entry)
		if err := copyPath(src, dst); err != nil {
			return fmt.Errorf("copy %s: %w", entry, err)
		}
	}
	if err := writeComponentsConfig(filepath.Join(outputDir, "configs", "components.yaml"), kebabName); err != nil {
		return err
	}
	if err := writeResourcesConfig(outputDir, kebabName); err != nil {
		return err
	}
	if err := writeSystemConfig(outputDir, templateRoot); err != nil {
		return err
	}
	if err := writeTestScript(filepath.Join(outputDir, "scripts", "test_api.sh"), kebabName); err != nil {
		return err
	}
	if err := writeSecretScript(outputDir, kebabName); err != nil {
		return err
	}

	arch, _ := getArch()
	if arch == "" {
		arch = "amd64"
	}
	configsPath := filepath.Join(outputDir, "configs", "project.env")
	envContent := fmt.Sprintf(`# Auto-generated by kp init for deploy
PROJECT_NAME=%s
KUBE_NAMESPACE=%s
KUBE_CONTEXT=
KUBE_CONFIG=
MODULE_PATH=%s
REGISTRY_PREFIX=qingchun22
ARCH=%s
VERSION=v0.1.0
ETCD_ENDPOINTS=
`, kebabName, kebabName, module, arch)
	if err := os.WriteFile(configsPath, []byte(envContent), 0644); err != nil {
		return fmt.Errorf("gen project.env: %w", err)
	}

	// Helm chart dirs
	renameDir(filepath.Join(outputDir, "deployments", "project"), filepath.Join(outputDir, "deployments", kebabName))
	renameDir(filepath.Join(outputDir, "deployments", "dev-toolkit"), filepath.Join(outputDir, "deployments", kebabName))
	fixChartYAMLs(outputDir, kebabName)
	writeHelmTemplateSkeleton(outputDir, kebabName)

	// Git init
	runInDir(outputDir, "git", "init", "--initial-branch=Master")
	runInDir(outputDir, "git", "add", ".")
	runInDir(outputDir, "git", "commit", "-m", "chore: init project by kp")

	// Phase 2: 壳层 — 语言相关应用骨架
	if !opts.NoApp {
		switch opts.Lang {
		case LangPython:
			if err := emitAppFromFS(pythonAppTemplates, "templates/python", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen python app: %w", err)
			}
		case LangJava:
			if err := emitAppFromFS(javaAppTemplates, "templates/java", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen java app: %w", err)
			}
		case LangRust:
			if err := emitAppFromFS(rustAppTemplates, "templates/rust", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen rust app: %w", err)
			}
		case LangCpp:
			if err := emitAppFromFS(cppAppTemplates, "templates/cpp", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen cpp app: %w", err)
			}
		case LangCS:
			if err := emitAppFromFS(csAppTemplates, "templates/cs", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen cs app: %w", err)
			}
		case LangZig:
			if err := emitAppFromFS(zigAppTemplates, "templates/zig", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen zig app: %w", err)
			}
		case LangKotlin:
			if err := emitAppFromFS(kotlinAppTemplates, "templates/kotlin", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen kotlin app: %w", err)
			}
		case LangTS:
			if err := emitAppFromFS(tsAppTemplates, "templates/ts", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen ts app: %w", err)
			}
		case LangPHP:
			if err := emitAppFromFS(phpAppTemplates, "templates/php", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen php app: %w", err)
			}
		case LangSwift:
			if err := emitAppFromFS(swiftAppTemplates, "templates/swift", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen swift app: %w", err)
			}
		case LangLua:
			if err := emitAppFromFS(luaAppTemplates, "templates/lua", outputDir, kebabName); err != nil {
				return fmt.Errorf("gen lua app: %w", err)
			}
		default:
			// Go（默认）— 现有完整骨架
			writeGoMod(filepath.Join(outputDir, "go.mod"), module)
			writeServiceMain(filepath.Join(outputDir, "cmd", kebabName, "main.go"), name)
			writeInternalSkeleton(outputDir, kebabName, module)
			writeMigrationSkeleton(outputDir, kebabName)
			writeAuthPackage(outputDir)
			writeMetricsSkeleton(outputDir, kebabName)
			writeMonitoringSkeleton(outputDir, kebabName)
			writeTestSkeleton(outputDir, kebabName)
			writeSnapshotSkeleton(outputDir, name)
			writeSwaggerSpec(outputDir, kebabName)
			writeHandoffSkeleton(outputDir, name, module, opts.WithFrontend)
			writeAICodingGuide(outputDir, name, module)

			renameDir(filepath.Join(outputDir, "build", "docker", "helloworld"), filepath.Join(outputDir, "build", "docker", kebabName))
			renameDir(filepath.Join(outputDir, "build", "docker", "kp"), filepath.Join(outputDir, "build", "docker", name))
			renameDir(filepath.Join(outputDir, "build", "docker", "dev-toolkit"), filepath.Join(outputDir, "build", "docker", kebabName))
			writeDockerfile(filepath.Join(outputDir, "build", "docker", kebabName, "Dockerfile"), kebabName)
			writeBuildSh(filepath.Join(outputDir, "build", "docker", kebabName, "build.sh"), kebabName)

			replacements := map[string]string{
				"github.com/Ixecd/kubepivot": module,
				"dev-toolkit":                kebabName,
			}
			replaceInDir(outputDir, replacements)
			_ = replaceInDir(filepath.Join(outputDir, ".githooks"), map[string]string{module: "github.com/Ixecd/kubepivot"})
			replaceInDir(filepath.Join(outputDir, "deployments"), map[string]string{"project": kebabName})

			runInDir(outputDir, "go", "get", "github.com/stretchr/testify@latest")
			runInDir(outputDir, "go", "get", "github.com/golang-jwt/jwt/v5")
			runInDir(outputDir, "go", "get", "golang.org/x/crypto/bcrypt")
			runInDir(outputDir, "go", "get", "github.com/prometheus/client_golang/prometheus")
			runInDir(outputDir, "go", "mod", "tidy")
		}
	}

	// 非 Go 语言：替换为多语言 Makefile + 整理 Dockerfile 路径
	if opts.Lang != "" && opts.Lang != LangGo {
		// 替换 Go Makefile 为多语言 Makefile（仅部署相关 target）
		writePolyglotMakefile(outputDir, kebabName, module)
		// Dockerfile + .dockerignore 从根目录移到 build/docker/<name>/
		dockerDir := filepath.Join(outputDir, "build", "docker", kebabName)
		os.MkdirAll(dockerDir, 0755)
		if _, err := os.Stat(filepath.Join(outputDir, "Dockerfile")); err == nil {
			os.Rename(filepath.Join(outputDir, "Dockerfile"),
				filepath.Join(dockerDir, "Dockerfile"))
		}
		if _, err := os.Stat(filepath.Join(outputDir, ".dockerignore")); err == nil {
			os.Rename(filepath.Join(outputDir, ".dockerignore"),
				filepath.Join(dockerDir, ".dockerignore"))
		}
	}

// Phase 3: 成功消息
	friendly := strings.Replace(friendlyPath(outputDir), kebabName, name, -1)
	fmt.Fprintf(opts.Stdout, "✅ 项目已成功生成！\n\n")
	fmt.Fprintf(opts.Stdout, "  路径    %s\n", friendly)
	fmt.Fprintf(opts.Stdout, "  模块    %s\n", module)
	if opts.Lang == "" || opts.Lang == LangGo {
		fmt.Fprintf(opts.Stdout, "  入口    cmd/%s\n\n", kebabName)
	}
	fmt.Fprintf(opts.Stdout, "下一步：\n")
	fmt.Fprintf(opts.Stdout, "  cd %s\n", friendly)
	fmt.Fprintf(opts.Stdout, "  make tools   # 安装所有工具\n")
	fmt.Fprintf(opts.Stdout, "  make build   # 编译\n")
	fmt.Fprintf(opts.Stdout, "  make test    # 测试\n")
	fmt.Fprintf(opts.Stdout, "\n🔱 接入 KubePivot Controller（自愈 / 漂移治理）：\n")
	fmt.Fprintf(opts.Stdout, "  1. 集群级安装（一次性）: kp controller install\n")
	fmt.Fprintf(opts.Stdout, "  2. 项目接入: kp controller enroll\n")
	fmt.Fprintf(opts.Stdout, "  3. 查看状态: kp controller status\n")
	fmt.Fprintf(opts.Stdout, "  按需编辑 configs/resources.yaml 声明要保护的资源\n")

	if opts.WithFrontend {
		if err := writeFrontendSkeleton(outputDir, name); err != nil {
			return fmt.Errorf("gen frontend: %w", err)
		}
		fmt.Fprintf(opts.Stdout, "  cd %s/frontend && npm install && npm run dev  # 前端\n", friendly)
	}
	return nil
}

func runInDir(dir string, name string, args ...string) error {
	slog.Debug("执行命令", "cmd", name, "args", args, "dir", dir)
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Stdout = io.Discard
	var errBuf strings.Builder
	cmd.Stderr = &errBuf
	err := cmd.Run()
	if err != nil {
		slog.Debug("命令执行失败",
			"cmd", name,
			"args", args,
			"stderr", strings.TrimSpace(errBuf.String()),
			"err", err,
		)
	}
	return err
}

// 新增辅助函数
func getArch() (string, error) {
	out, err := exec.Command("go", "env", "GOARCH").Output()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(out)), nil
}

func fixChartYAMLs(root, name string) {
	path := filepath.Join(root, "deployments", name, "Chart.yaml")
	data, err := os.ReadFile(path)
	if err != nil {
		return
	}

	lines := strings.Split(string(data), "\n")
	var result []string
	inDeps := false
	depsReplaced := false

	for _, line := range lines {
		if strings.HasPrefix(line, "dependencies:") && !depsReplaced {
			inDeps = true
			result = append(result, "dependencies: []")
			depsReplaced = true
			continue
		}
		if inDeps {
			// 依赖块以非缩进行结束
			if len(line) > 0 && line[0] != ' ' && line[0] != '\t' && line[0] != '-' {
				inDeps = false
				result = append(result, line)
			}
			// 跳过依赖块内容
			continue
		}
		result = append(result, line)
	}

	os.WriteFile(path, []byte(strings.Join(result, "\n")), 0644)
}

func resolveTemplateRoot(explicit string) (string, error) {
	if explicit != "" {
		return filepath.Abs(explicit)
	}
	// 优先使用内嵌模板（go install 后无需配置）
	if tmpDir, err := ExtractEmbeddedTemplates(); err == nil {
		return tmpDir, nil
	}
	// 降级：环境变量覆盖
	if env := strings.TrimSpace(os.Getenv("KP_TEMPLATE_ROOT")); env != "" {
		return filepath.Abs(env)
	}
	return "", errors.New("template root not found: use --template or set KP_TEMPLATE_ROOT")
}

func resolveOutputDir(explicit, name string) (string, error) {
	if explicit == "" {
		explicit = name
	}
	return filepath.Abs(explicit)
}

func ensureOutputDir(path string, force bool, name string) error {
	info, err := os.Stat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return os.MkdirAll(path, 0o755)
		}
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("输出路径存在但不是目录：%s", friendlyPath(path))
	}

	// === 新增严格检查：目录已存在时默认直接失败（保护用户项目）===
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	if len(entries) > 0 || !force {
		// 即使是空目录，也建议用户加 --force（更明确）
		if force {
			// force=true 时允许继续（会覆盖）
			return nil
		}
		return fmt.Errorf("输出目录已存在：%s\n\n"+
			"   请使用其他路径，或加 --force 强制覆盖：\n"+
			"     kp init --name %s --output %s --force",
			friendlyPath(path), name, friendlyPath(path)) // 这里 name 是 InitProject 里的局部变量
	}
	return nil
}

func copyPath(src, dst string) error {
	info, err := os.Stat(src)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if shouldSkip(filepath.Base(src)) {
		return nil
	}
	if info.IsDir() {
		return copyDir(src, dst)
	}
	return copyFile(src, dst)
}

func copyDir(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		base := filepath.Base(path)
		if shouldSkip(base) {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		return copyFile(path, target)
	})
}

func copyFile(src, dst string) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()

	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()

	if _, err := io.Copy(out, in); err != nil {
		return err
	}
	return out.Close()
}

func renameDir(oldPath, newPath string) error {
	// 源目录不存在就跳过（模板里可能没有）
	if _, err := os.Stat(oldPath); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	// === 目标已存在时自动清理（--force 模式下安全）===
	if _, err := os.Stat(newPath); err == nil {
		if err := os.RemoveAll(newPath); err != nil {
			return fmt.Errorf("清理旧目录失败 %s: %w", newPath, err)
		}
	}

	if err := os.MkdirAll(filepath.Dir(newPath), 0o755); err != nil {
		return err
	}
	return os.Rename(oldPath, newPath)
}

func isText(data []byte) bool {
	if !utf8.Valid(data) {
		return false
	}
	return !bytesContainsZero(data)
}

func bytesContainsZero(data []byte) bool {
	for _, b := range data {
		if b == 0 {
			return true
		}
	}
	return false
}

func shouldSkip(name string) bool {
	switch name {
	case ".git", ".cursor", "_output", "node_modules", ".DS_Store":
		return true
	default:
		return false
	}
}

func replaceInDir(root string, replacements map[string]string) error {
	// 目录不存在时优雅跳过
	// 常见于模板中没有 deployments/project 子目录的情况
	if _, err := os.Stat(root); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	return filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if shouldSkip(filepath.Base(path)) {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.IsDir() {
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !isText(data) {
			return nil
		}

		// 按 key 长度降序排序，长的先替换，避免短 key 破坏长 key
		keys := make([]string, 0, len(replacements))
		for k := range replacements {
			keys = append(keys, k)
		}
		sort.Slice(keys, func(i, j int) bool {
			return len(keys[i]) > len(keys[j])
		})

		updated := string(data)
		for _, k := range keys {
			updated = strings.ReplaceAll(updated, k, replacements[k])
		}

		if updated == string(data) {
			return nil
		}
		return os.WriteFile(path, []byte(updated), 0o644)
	})
}

// emitAppFromFS 通用应用骨架发射器，从 embed.FS 读取模板文件写入输出目录。
func emitAppFromFS(fs embed.FS, root string, outputDir, name string) error {
	return walkEmbedDir(fs, root, outputDir, name)
}

func walkEmbedDir(fs embed.FS, dir, outputDir, name string) error {
	entries, err := fs.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		srcPath := dir + "/" + e.Name()
		if e.IsDir() {
			subName := filepath.Base(srcPath)
			targetDir := filepath.Join(outputDir, subName)
			os.MkdirAll(targetDir, 0755)
			if err := walkEmbedDir(fs, srcPath, targetDir, name); err != nil {
				return err
			}
			continue
		}
		data, err := fs.ReadFile(srcPath)
		if err != nil {
			return err
		}
		content := strings.ReplaceAll(string(data), "{{name}}", name)
		content = strings.ReplaceAll(content, "{{.Port}}", "8080")
		dst := filepath.Join(outputDir, e.Name())
		if err := os.WriteFile(dst, []byte(content), 0644); err != nil {
			return err
		}
	}
	return nil
}

// writePolyglotMakefile 为非 Go 项目写最小 Makefile，仅支持 deploy.build / deploy.push。
func writePolyglotMakefile(outputDir, name, module string) error {
	content := fmt.Sprintf(`# %s — KubePivot 多语言项目 Makefile

ROOT_DIR := $(shell pwd)
VERSION ?= v0.1.0
ARCH ?= amd64
REGISTRY_PREFIX ?= qingchun22
PROJECT_NAME := %s
MODULE_PATH := %s
DOCKERFILE := build/docker/$(PROJECT_NAME)/Dockerfile

include scripts/make-rules/deploy.mk

.PHONY: deploy.build deploy.push
deploy.build:
	@docker build -t $(REGISTRY_PREFIX)/$(PROJECT_NAME)-$(ARCH):$(VERSION) -f $(DOCKERFILE) .

deploy.push:
	@docker push $(REGISTRY_PREFIX)/$(PROJECT_NAME)-$(ARCH):$(VERSION)
`, name, name, module)

	return os.WriteFile(filepath.Join(outputDir, "Makefile"), []byte(content), 0644)
}

// friendlyPath 把绝对路径转成用户友好的形式
// 优先显示 ~/myproject，其次显示相对路径
func friendlyPath(absPath string) string {
	home, err := os.UserHomeDir()
	if err == nil {
		home = filepath.Clean(home)
		abs := filepath.Clean(absPath)
		if strings.HasPrefix(abs, home) {
			rel := strings.TrimPrefix(abs, home)
			rel = strings.TrimPrefix(rel, string(filepath.Separator))
			if rel == "" {
				return "~"
			}
			return "~/" + filepath.ToSlash(rel)
		}
	}

	// 尝试转为相对当前目录
	if cwd, err := os.Getwd(); err == nil {
		if rel, err := filepath.Rel(cwd, absPath); err == nil && !strings.HasPrefix(rel, "..") {
			return filepath.ToSlash(rel)
		}
	}
	return absPath
}

// writeResourcesConfig 生成 configs/resources.yaml
// controller 依赖此文件决定监控哪些 K8s 资源
func writeResourcesConfig(outputDir, name string) error {
	var b strings.Builder
	b.WriteString("# configs/resources.yaml\n")
	b.WriteString("# A2 Reconciliation Controller 监控的 K8s 资源列表\n")
	b.WriteString("# 新增监控资源只需在此加一行，不需要改代码\n")
	b.WriteString("#\n")
	b.WriteString("# 支持的 kind：Deployment / StatefulSet / Service / PVC / Ingress / CronJob\n")
	b.WriteString("# on-missing 策略：\n")
	b.WriteString("#   auto-heal  — 自动执行 helm rollback 恢复\n")
	b.WriteString("#   alert      — 只告警，不自动处理\n")
	b.WriteString("#\n\n")
	b.WriteString("resources:\n")
	b.WriteString("  - kind: Deployment\n")
	b.WriteString("    name: " + name + "\n")
	b.WriteString("    on-missing: auto-heal\n")
	b.WriteString("    max-retry: 3\n")
	b.WriteString("    fallback: rollback\n")
	b.WriteString("\n")
	b.WriteString("  # 示例：监控 StatefulSet\n")
	b.WriteString("  # - kind: StatefulSet\n")
	b.WriteString("  #   name: " + name + "-postgres\n")
	b.WriteString("  #   on-missing: auto-heal\n")
	b.WriteString("  #   max-retry: 2\n")
	b.WriteString("  #   fallback: rollback\n")
	b.WriteString("\n")
	b.WriteString("  # 示例：只告警不自动处理\n")
	b.WriteString("  # - kind: PersistentVolumeClaim\n")
	b.WriteString("  #   name: postgres-data\n")
	b.WriteString("  #   on-missing: alert\n")

	path := filepath.Join(outputDir, "configs", "resources.yaml")
	if err := os.WriteFile(path, []byte(b.String()), 0644); err != nil {
		return fmt.Errorf("写入 resources.yaml 失败: %w", err)
	}
	return nil
}

// writeSystemConfig 拷贝 configs/system.yaml 到项目
// 优先从模板根目录读取（embed 和本地 --template 都能用），
// 找不到则从仓库 configs/system.yaml 降级读取
func writeSystemConfig(outputDir, templateRoot string) error {
	data, err := os.ReadFile(filepath.Join(templateRoot, "configs", "system.yaml"))
	if err != nil {
		data, err = os.ReadFile(filepath.Join("configs", "system.yaml"))
		if err != nil {
			return fmt.Errorf("读取 system.yaml 模板失败: %w", err)
		}
	}
	dst := filepath.Join(outputDir, "configs", "system.yaml")
	if err := os.WriteFile(dst, data, 0644); err != nil {
		return fmt.Errorf("写入 system.yaml 失败: %w", err)
	}
	return nil
}

func printDryRun(opts InitOptions) {
	outputDir := opts.OutputDir
	if outputDir == "" {
		outputDir = "./" + opts.Name
	}
	module := opts.Module
	if module == "" {
		module = opts.Name
	}

	fmt.Fprintf(opts.Stdout, "[dry-run] kp init --name %s --module %s\n\n", opts.Name, module)
	fmt.Fprintf(opts.Stdout, "将生成项目：%s\n", outputDir)
	fmt.Fprintf(opts.Stdout, "  模块路径：%s\n", module)
	fmt.Fprintf(opts.Stdout, "  前端骨架：%s\n\n", map[bool]string{true: "是", false: "否"}[opts.WithFrontend])

	n := opts.Name
	lines := []string{
		n + "/",
		"├── cmd/" + n + "/",
		"├── internal/",
		"│   ├── api/",
		"│   ├── auth/",
		"│   ├── metrics/",
		"│   └── db/migrations/",
		"├── configs/",
		"│   ├── project.env",
		"│   └── components.yaml",
		"├── deployments/" + n + "/",
		"│   ├── " + n + "-postgres/",
		"│   ├── " + n + "-etcd/",
		"│   ├── " + n + "/",
		"│   └── " + n + "-controller/",
		"├── monitoring/",
		"├── build/docker/" + n + "/",
		"├── test/",
		"├── scripts/",
		"│   └── create-secret.sh",
		"├── handoff/",
		"└── snapshots/",
	}
	if opts.WithFrontend {
		lines = append(lines[:len(lines)-1],
			"├── frontend/",
			"└── snapshots/",
		)
	}

	fmt.Fprintln(opts.Stdout, "目录结构：")
	for _, l := range lines {
		fmt.Fprintf(opts.Stdout, "  %s\n", l)
	}
	fmt.Fprintln(opts.Stdout)
	fmt.Fprintln(opts.Stdout, "不会执行：go mod tidy / git init / git commit / 文件写入")
}