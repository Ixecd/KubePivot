type InitOptions struct {
	Name         string
	Module       string
	OutputDir    string
	TemplateRoot string
	Force        bool
	WithFrontend bool
	Stdout       io.Writer
}

var (
	projectNamePattern = regexp.MustCompile(`^[a-z0-9-]+$`)
	copyEntries        = []string{
		".editorconfig",
		".gitignore",
		".gitlint",
		".golangci.yaml",
		".vscode",
		"build",
		"configs",
		"deployments",
		"docs",
		"githooks",
		"scripts",
		"templates",
		"tools",
		"docker-compose.yml",
		"LICENSE",
		"Makefile",
		"README.md",
	}
)

func InitProject(opts InitOptions) (err error) {
	name := strings.TrimSpace(opts.Name)
	if name == "" {
		return errors.New("missing project name: use --name")
	}
	if !projectNamePattern.MatchString(name) {
		return fmt.Errorf("invalid project name %q: use lowercase letters, numbers, and '-' only", name)
	}
	module := strings.TrimSpace(opts.Module)
	if module == "" {
		module = name
	}
	if opts.Stdout == nil {
		opts.Stdout = io.Discard
	}

	templateRoot, err := resolveTemplateRoot(opts.TemplateRoot)
	if err != nil {
		return err
	}

	outputDir, err := resolveOutputDir(opts.OutputDir, name)
	if err != nil {
		return err
	}

	// 记录目录是否由本次 init 创建
	// --force 时目录已存在，失败不能删（里面可能有用户文件）
	_, statErr := os.Stat(outputDir)
	createdByUs := os.IsNotExist(statErr) && !opts.Force

	if err = ensureOutputDir(outputDir, opts.Force, name); err != nil {
		return err
	}

	// 初始化失败时自动清理半成品目录
	defer func() {
		if err != nil && createdByUs {
			slog.Debug("初始化失败，清理半成品目录", "dir", outputDir)
			if removeErr := os.RemoveAll(outputDir); removeErr != nil {
				slog.Debug("清理失败", "dir", outputDir, "err", removeErr)
				return
			}
			fmt.Fprintf(opts.Stdout, "⚠️  初始化失败，已自动清理：%s\n", friendlyPath(outputDir))
		}
	}()

	for _, entry := range copyEntries {
		src := filepath.Join(templateRoot, entry)
		dst := filepath.Join(outputDir, entry)
		if err := copyPath(src, dst); err != nil {
			return fmt.Errorf("copy %s: %w", entry, err)
		}
	}

	if err := writeGoMod(filepath.Join(templateRoot, "go.mod"), filepath.Join(outputDir, "go.mod"), module); err != nil {
		return err
	}
	if err := writeServiceMain(filepath.Join(outputDir, "cmd", name, "main.go"), name); err != nil {
		return err
	}
	if err := writeComponentsConfig(filepath.Join(outputDir, "configs", "components.yaml"), name); err != nil {
		return err
	}
	if err := writeResourcesConfig(outputDir, name); err != nil {
		return err
	}
	if err := writeTestScript(filepath.Join(outputDir, "scripts", "test_api.sh"), name); err != nil {
		return err
	}
	if err := writeInternalSkeleton(outputDir, name, module); err != nil {
		return err
	}
	if err := writeMigrationSkeleton(outputDir, name); err != nil {
		return err
	}
	if err := writeAuthPackage(outputDir); err != nil {
		return err
	}
	if err := writeMetricsSkeleton(outputDir, name); err != nil {
		return err
	}
	if err := writeMonitoringSkeleton(outputDir, name); err != nil {
		return err
	}
	if err := writeTestSkeleton(outputDir, name, module); err != nil {
		return err
	}
	if err := writeSnapshotSkeleton(outputDir, name); err != nil {
		return err
	}
	if err := writeSwaggerSpec(outputDir, name); err != nil {
		return err
	}
	if err := writeHandoffSkeleton(outputDir, name, module, opts.WithFrontend); err != nil {
		return err
	}

	// 🔥 FIXED: gen project.env for deploy (raw string)
	configsPath := filepath.Join(outputDir, "configs", "project.env")
	envContent := fmt.Sprintf(`# Auto-generated by dtk init for deploy
PROJECT_NAME=%s
KUBE_NAMESPACE=%s
KUBE_CONTEXT=
KUBE_CONFIG=
MODULE_PATH=%s
REGISTRY_PREFIX=qingchun22
ARCH=arm64
VERSION=v0.1.0
ETCD_ENDPOINTS=
`, name, name, module)
	if err := os.WriteFile(configsPath, []byte(envContent), 0644); err != nil {
		return fmt.Errorf("gen project.env: %w", err)
	}

	if err := renameDir(filepath.Join(outputDir, "build", "docker", "helloworld"), filepath.Join(outputDir, "build", "docker", name)); err != nil {
		return err
	}
	if err := renameDir(filepath.Join(outputDir, "build", "docker", "dtk"), filepath.Join(outputDir, "build", "docker", name)); err != nil {
		// ignore if not exist
	}
	if err := renameDir(filepath.Join(outputDir, "deployments", "project"), filepath.Join(outputDir, "deployments", name)); err != nil {
		return err
	}

	if err := writeDockerfile(filepath.Join(outputDir, "build", "docker", name, "Dockerfile"), name); err != nil {
		return err
	}
	if err := writeBuildSh(filepath.Join(outputDir, "build", "docker", name, "build.sh"), name); err != nil {
		return err
	}

	replacements := map[string]string{
		"github.com/Ixecd/dev-toolkit": module,
		"dev-toolkit":                  name,
	}

	if err := replaceInDir(outputDir, replacements); err != nil {
		return fmt.Errorf("content replacement failed: %w", err)
	}

	if err := replaceInDir(filepath.Join(outputDir, "deployments"), map[string]string{
		"project": name,
	}); err != nil {
		return fmt.Errorf("fix helm chart templates: %w", err)
	}

	// after replaceInDir
	fixChartYAMLs(outputDir, name)

	if err := writeHelmTemplateSkeleton(outputDir, name); err != nil {
		return err
	}

	// 🔥 ADD dir renames漏
	if err := renameDir(filepath.Join(outputDir, "deployments", "dev-toolkit"), filepath.Join(outputDir, "deployments", name)); err != nil {
		// ignore if not exist
	}
	if err := renameDir(filepath.Join(outputDir, "build", "docker", "dev-toolkit"), filepath.Join(outputDir, "build", "docker", name)); err != nil {
	}

	// 自动安装依赖
	if err := runInDir(outputDir, "git", "init"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] git init 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "git", "add", "."); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] git add 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "git", "commit", "-m", "chore: init project by dtk"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] git commit 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "go", "get", "github.com/stretchr/testify@latest"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] go get testify 失败，请手动执行: go get github.com/stretchr/testify\n")
	}
	if err := runInDir(outputDir, "go", "get", "github.com/golang-jwt/jwt/v5"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] go get jwt 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "go", "get", "golang.org/x/crypto/bcrypt"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] go get bcrypt 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "go", "get", "github.com/prometheus/client_golang/prometheus"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] go get prometheus 失败，请手动执行\n")
	}
	if err := runInDir(outputDir, "go", "mod", "tidy"); err != nil {
		fmt.Fprintf(opts.Stdout, "[WARN] go mod tidy 失败，请手动执行\n")
	}

	// 友好路径显示（~/myproject 而不是绝对路径）
	friendly := friendlyPath(outputDir)

	fmt.Fprintf(opts.Stdout, "✅ 项目已成功生成！\n\n")
	fmt.Fprintf(opts.Stdout, "  路径    %s\n", friendly)
	fmt.Fprintf(opts.Stdout, "  模块    %s\n", module)
	fmt.Fprintf(opts.Stdout, "  入口    cmd/%s\n\n", name)
	fmt.Fprintf(opts.Stdout, "下一步：\n")
	fmt.Fprintf(opts.Stdout, "  cd %s\n", friendly)
	fmt.Fprintf(opts.Stdout, "  make tools   # 安装所有工具\n")
	fmt.Fprintf(opts.Stdout, "  make build   # 编译\n")
	fmt.Fprintf(opts.Stdout, "  make test    # 测试\n")
	fmt.Fprintf(opts.Stdout, "\n⚠️  上线前请检查：\n")
	fmt.Fprintf(opts.Stdout, "  deployments/%s/templates/controller-rbac.yaml\n", name)
	fmt.Fprintf(opts.Stdout, "  → 当前为全量权限，请按实际需要收紧 ClusterRole rules\n")
	fmt.Fprintf(opts.Stdout, "  deployments/%s/templates/controller-deployment.yaml\n", name)
	fmt.Fprintf(opts.Stdout, "  → 替换 controller.image.repository 为你构建的镜像\n")

	if opts.WithFrontend {
		if err := writeFrontendSkeleton(outputDir, name); err != nil {
			return fmt.Errorf("gen frontend: %w", err)
		}
		fmt.Fprintf(opts.Stdout, "  cd %s/frontend && npm install && npm run dev  # 前端\n", friendly)
	}
	return nil
}

func runInDir(dir string, name string, args ...string) error {
	slog.Debug("执行命令", "cmd", name, "args", args, "dir", dir)
	cmd := exec.Command(name, args...)
	cmd.Dir = dir
	cmd.Stdout = io.Discard
	var errBuf strings.Builder
	cmd.Stderr = &errBuf
	err := cmd.Run()
	if err != nil {
		slog.Debug("命令执行失败",
			"cmd", name,
			"args", args,
			"stderr", strings.TrimSpace(errBuf.String()),
			"err", err,
		)
	}
	return err
}

func fixChartYAMLs(root, name string) {
	path := filepath.Join(root, "deployments", name, "Chart.yaml")
	data, err := os.ReadFile(path)
	if err != nil {
		return
	}
	// 清理 dependencies
	updated := regexp.MustCompile(`(?s)dependencies:.*?(?=maintainers:|annotations:|type:|\z)`).
		ReplaceAllString(string(data), "dependencies: []\n")
	os.WriteFile(path, []byte(updated), 0644)
}

func resolveTemplateRoot(explicit string) (string, error) {
	if explicit != "" {
		return filepath.Abs(explicit)
	}
	if env := strings.TrimSpace(os.Getenv("DTK_TEMPLATE_ROOT")); env != "" {
		return filepath.Abs(env)
	}

	cwd, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get cwd: %w", err)
	}
	if isTemplateRoot(cwd) {
		return cwd, nil
	}
	return "", errors.New("template root not found: use --template or set DTK_TEMPLATE_ROOT")
}

func isTemplateRoot(path string) bool {
	required := []string{
		"Makefile",
		filepath.Join("scripts", "make-rules", "common.mk"),
		filepath.Join("githooks", "pre-commit.sh"),
	}
	for _, item := range required {
		if _, err := os.Stat(filepath.Join(path, item)); err != nil {
			return false
		}
	}
	return true
}

func resolveOutputDir(explicit, name string) (string, error) {
	if explicit == "" {
		explicit = name
	}
	return filepath.Abs(explicit)
}

func ensureOutputDir(path string, force bool, name string) error {
	info, err := os.Stat(path)
	if err != nil {
		if os.IsNotExist(err) {
			return os.MkdirAll(path, 0o755)
		}
		return err
	}
	if !info.IsDir() {
		return fmt.Errorf("输出路径存在但不是目录：%s", friendlyPath(path))
	}

	// === 新增严格检查：目录已存在时默认直接失败（保护用户项目）===
	entries, err := os.ReadDir(path)
	if err != nil {
		return err
	}
	if len(entries) > 0 || !force {
		// 即使是空目录，也建议用户加 --force（更明确）
		if force {
			// force=true 时允许继续（会覆盖）
			return nil
		}
		return fmt.Errorf("输出目录已存在：%s\n\n"+
			"   请使用其他路径，或加 --force 强制覆盖：\n"+
			"     dtk init --name %s --output %s --force",
			friendlyPath(path), name, friendlyPath(path)) // 这里 name 是 InitProject 里的局部变量
	}
	return nil
}

func copyPath(src, dst string) error {
	info, err := os.Stat(src)
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	if shouldSkip(filepath.Base(src)) {
		return nil
	}
	if info.IsDir() {
		return copyDir(src, dst)
	}
	return copyFile(src, dst)
}

func copyDir(src, dst string) error {
	return filepath.WalkDir(src, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		base := filepath.Base(path)
		if shouldSkip(base) {
			if d.IsDir() {
				return filepath.SkipDir
			}
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		rel, err := filepath.Rel(src, path)
		if err != nil {
			return err
		}
		target := filepath.Join(dst, rel)
		if d.IsDir() {
			return os.MkdirAll(target, 0o755)
		}
		return copyFile(path, target)
	})
}

func copyFile(src, dst string) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	in, err := os.Open(src)
	if err != nil {
		return err
	}
	defer in.Close()

	out, err := os.Create(dst)
	if err != nil {
		return err
	}
	defer out.Close()

	if _, err := io.Copy(out, in); err != nil {
		return err
	}
	return out.Close()
}

func renameDir(oldPath, newPath string) error {
	// 源目录不存在就跳过（模板里可能没有）
	if _, err := os.Stat(oldPath); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	// === 目标已存在时自动清理（--force 模式下安全）===
	if _, err := os.Stat(newPath); err == nil {
		if err := os.RemoveAll(newPath); err != nil {
			return fmt.Errorf("清理旧目录失败 %s: %w", newPath, err)
		}
	}

	if err := os.MkdirAll(filepath.Dir(newPath), 0o755); err != nil {
		return err
	}
	return os.Rename(oldPath, newPath)
}

func isText(data []byte) bool {
	if !utf8.Valid(data) {
		return false
	}
	return !bytesContainsZero(data)
}

func bytesContainsZero(data []byte) bool {
	for _, b := range data {
		if b == 0 {
			return true
		}
	}
	return false
}

func shouldSkip(name string) bool {
	switch name {
	case ".git", ".cursor", "_output", "node_modules", ".DS_Store":
		return true
	default:
		return false
	}
}

func replaceInDir(root string, replacements map[string]string) error {
	// 目录不存在时优雅跳过
	// 常见于模板中没有 deployments/project 子目录的情况
	if _, err := os.Stat(root); err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}

	return filepath.WalkDir(root, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() {
			return nil
		}
		if d.Type()&os.ModeSymlink != 0 {
			return nil
		}
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !isText(data) {
			return nil
		}
		updated := string(data)
		for oldValue, newValue := range replacements {
			updated = strings.ReplaceAll(updated, oldValue, newValue)
		}
		if updated == string(data) {
			return nil
		}
		return os.WriteFile(path, []byte(updated), 0o644)
	})
}

// friendlyPath 把绝对路径转成用户友好的形式
// 优先显示 ~/myproject，其次显示相对路径
func friendlyPath(absPath string) string {
	home, err := os.UserHomeDir()
	if err == nil {
		home = filepath.Clean(home)
		abs := filepath.Clean(absPath)
		if strings.HasPrefix(abs, home) {
			rel := strings.TrimPrefix(abs, home)
			rel = strings.TrimPrefix(rel, string(filepath.Separator))
			if rel == "" {
				return "~"
			}
			return "~/" + filepath.ToSlash(rel)
		}
	}

	// 尝试转为相对当前目录
	if cwd, err := os.Getwd(); err == nil {
		if rel, err := filepath.Rel(cwd, absPath); err == nil && !strings.HasPrefix(rel, "..") {
			return filepath.ToSlash(rel)
		}
	}
	return absPath
}

